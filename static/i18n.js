function detectLanguage() {
  const saved = localStorage.getItem('g834jz-language');
  if (saved === 'pl' || saved === 'en') return saved;
  return (navigator.language || '').toLowerCase().startsWith('pl') ? 'pl' : 'en';
}

let currentLanguage = detectLanguage();

function t(key, vars = {}) {
  let value = I18N[currentLanguage]?.[key] ?? I18N.en[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

function translateServerMessage(message) {
  const key = SERVER_MESSAGE_KEYS[String(message || '')];
  return key ? t(key) : message;
}

function translateProfileDescription(description) {
  const d = String(description || '');
  if (d === 'Aktualny sprawdzony profil G834JZ') return t('desc_final');
  if (d === 'Spokojniejszy profil: klawisze 1–8 fioletowe') return t('desc_daily');

  const prefixes = ['Profil utworzony na podstawie: ', 'Profile created from: '];
  for (const prefix of prefixes) {
    if (d.startsWith(prefix)) return t('desc_created_from', {name: d.slice(prefix.length)});
  }
  return d;
}

function translateServiceState(state) {
  const s = String(state || '').toLowerCase();
  if (s === 'active') return t('state_active');
  if (s === 'inactive') return t('state_inactive');
  if (s === 'failed') return t('state_failed');
  return s || t('state_unknown');
}

function translateAsusProfile(name) {
  if (name === 'CICHY') return t('asus_quiet');
  return name;
}

function applyTranslations(root = document) {
  document.documentElement.lang = currentLanguage;

  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });

  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  root.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });

  document.querySelectorAll('.lang-button').forEach(btn => {
    const active = btn.dataset.lang === currentLanguage;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', active ? 'true' : 'false');
  });
}

function setLanguage(lang) {
  if (lang !== 'pl' && lang !== 'en') return;
  currentLanguage = lang;
  localStorage.setItem('g834jz-language', lang);
  applyTranslations();
  window.dispatchEvent(new CustomEvent('languagechange', {detail: {lang}}));
}

function getLanguage() {
  return currentLanguage;
}

window.t = t;
window.setLanguage = setLanguage;
window.getLanguage = getLanguage;
window.applyTranslations = applyTranslations;
window.translateServerMessage = translateServerMessage;
window.translateProfileDescription = translateProfileDescription;
window.translateServiceState = translateServiceState;
window.translateAsusProfile = translateAsusProfile;

document.querySelectorAll('.lang-button').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});

applyTranslations();
